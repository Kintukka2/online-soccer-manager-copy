/* The service worker.
   ------------------------------------------------------------------
   This is a second cache sitting on top of one that was already carefully
   designed, and the two have to agree or the app breaks in the worst way it
   can: half of it new, half of it a year old.

   The existing scheme, from _headers and VERSIONING.md: every css/ and js/
   URL carries ?v=<VERSION> and is immutable for a year, and the HTML is
   never cached, because the stamps live in the HTML. A browser holding a
   stale index.html never learns the new asset URLs and keeps its old code
   forever.

   A naive service worker breaks exactly that. Precache index.html, serve it
   cache-first, and every returning visitor is pinned to whatever version
   they first installed -- the same failure _headers exists to prevent,
   except this one survives a hard refresh.

   So:

   - The cache name carries the version. A new release is a new cache, and
     the old one is deleted on activate. Nothing is ever served from the
     previous release's cache.
   - PRECACHE below is GENERATED by tools/stamp-assets.js, which already
     walks every page and every asset URL. A hand-written list drifts, and a
     drifted list is what serves new CSS against old JS.
   - Navigations go to the network first and fall back to the cache. That
     keeps "the HTML always revalidates" true whenever there is a connection,
     and gives offline when there is not.
   - Stamped assets go cache-first, which is safe by construction: the URL
     changes whenever the bytes do. That is the same claim `immutable`
     already makes.
   - Third parties are never intercepted. Caching somebody else's response
     is not ours to do, and a request we never touch cannot be broken by us.
   - Fonts are the one exception, in a cache of their own that is not keyed
     to our version, because Google's font files do not change when we
     release and re-downloading them every version would be waste. Without
     this the display face falls back to a system sans the moment you are
     offline, which is the most visible way the app can look broken. */

'use strict';

/* PRECACHE:START — generated by tools/stamp-assets.js, do not edit by hand */
var VERSION = '0.1.0';
var PRECACHE = [
  '/',
  '/404.html',
  '/apple-touch-icon.png',
  '/css/styles.css?v=0.1.0',
  '/icon-192.png',
  '/icon-512.png',
  '/icon-maskable-512.png',
  '/js/app.js?v=0.1.0',
  '/js/board.js?v=0.1.0',
  '/js/data.js?v=0.1.0',
  '/js/engine.js?v=0.1.0',
  '/js/store.js?v=0.1.0',
  '/js/ui.js?v=0.1.0',
  '/manifest.json',
  '/og.png'
];
/* PRECACHE:END */

var SHELL = 'osmwiz-shell-' + VERSION;
var FONTS = 'osmwiz-fonts';

// Everything we will not touch. Requests to these go straight to the
// network as if this worker did not exist.
function isThirdParty(url) {
  return url.origin !== self.location.origin;
}

function isFont(url) {
  return url.host === 'fonts.googleapis.com' || url.host === 'fonts.gstatic.com';
}

// A stamped asset: the URL changes when the file does, so the cached copy
// can never be the wrong copy.
function isStamped(url) {
  return /^\/(css|js)\//.test(url.pathname) && url.searchParams.has('v');
}

self.addEventListener('install', function (e) {
  e.waitUntil(
    caches.open(SHELL).then(function (cache) {
      // addAll is all-or-nothing, which is the behaviour we want: a
      // half-populated shell cache is worse than none, because it would
      // serve some pages offline and fail on others with no pattern.
      return cache.addAll(PRECACHE);
    }).then(function () {
      // Take over as soon as the new copy is ready rather than waiting for
      // every tab to close. Safe here because the cache is version-keyed:
      // there is no old-worker-serving-new-assets window to fall into.
      return self.skipWaiting();
    })
  );
});

self.addEventListener('activate', function (e) {
  e.waitUntil(
    caches.keys().then(function (names) {
      return Promise.all(names.map(function (name) {
        // Ours, from a previous release. The font cache is deliberately not
        // matched here: it does not belong to a version.
        if (name.indexOf('osmwiz-shell-') === 0 && name !== SHELL) {
          return caches.delete(name);
        }
        return null;
      }));
    }).then(function () {
      return self.clients.claim();
    })
  );
});

self.addEventListener('fetch', function (e) {
  var req = e.request;
  if (req.method !== 'GET') return;

  var url = new URL(req.url);

  if (isThirdParty(url)) {
    if (isFont(url)) e.respondWith(fontFirst(req));
    return;                       // everything else goes to the network untouched
  }

  if (req.mode === 'navigate') {
    e.respondWith(networkFirst(req));
    return;
  }

  if (isStamped(url)) {
    e.respondWith(cacheFirst(req, SHELL));
    return;
  }

  // Anything else of ours -- icons, the manifest, og.png. Cache them when
  // they arrive, but always prefer a fresh copy, because none of them
  // carries a version in its URL.
  e.respondWith(networkFirst(req));
});

function cacheFirst(req, cacheName) {
  return caches.match(req).then(function (hit) {
    if (hit) return hit;
    return fetch(req).then(function (res) {
      if (res && res.ok) {
        var copy = res.clone();
        caches.open(cacheName).then(function (c) { c.put(req, copy); });
      }
      return res;
    });
  });
}

function networkFirst(req) {
  return fetch(req).then(function (res) {
    if (res && res.ok) {
      var copy = res.clone();
      caches.open(SHELL).then(function (c) { c.put(req, copy); });
    }
    return res;
  }).catch(function () {
    return caches.match(req).then(function (hit) {
      if (hit) return hit;
      // An address we have never held, with no connection to go and get it.
      // The home page is cached and routes on the hash, so it is a better
      // answer than the browser's own offline page.
      if (req.mode === 'navigate') return caches.match('/');
      return Response.error();
    });
  });
}

// Opaque responses cannot be inspected, so `res.ok` is false for a font even
// when it arrived fine. Cache it anyway: a font either renders or it does
// not, and a bad one costs a fallback face rather than a broken app.
function fontFirst(req) {
  return caches.match(req).then(function (hit) {
    if (hit) return hit;
    return fetch(req).then(function (res) {
      var copy = res.clone();
      caches.open(FONTS).then(function (c) { c.put(req, copy); });
      return res;
    });
  });
}
